// Builds src/components/holo/human-data.ts from the MakeHuman base mesh (CC0).
//
// Usage: node scripts/build-human-mesh.mjs <dir>
//   <dir>/base.obj                         makehuman/data/3dobjs/base.obj (makehumancommunity/makehuman)
//   <dir>/{african,asian,caucasian}-{female,male}.gz   macrodetails/<race>-<gender>-young.target.gz (makehumancommunity/mpfb2)
//
// Both the base mesh and the targets were released by the MakeHuman project under CC0 1.0.
// Female / male = base mesh + the average of the three young race targets of that gender
// (what MakeHuman shows for gender 0 / 1 with default settings).
import { readFileSync, writeFileSync } from "node:fs";
import { gunzipSync } from "node:zlib";
import path from "node:path";

const dir = process.argv[2];
if (!dir) { console.error("Bitte Ordner mit base.obj und Targets angeben"); process.exit(1); }
const root = path.resolve(import.meta.dirname, "..");

const verts = [];
const groups = {}; // group -> Set of vertex indices
const bodyFaces = [];
let group = "";
for (const line of readFileSync(path.join(dir, "base.obj"), "utf8").split("\n")) {
  if (line.startsWith("v ")) { const [, x, y, z] = line.trim().split(/\s+/); verts.push([+x, +y, +z]); }
  else if (line.startsWith("g ")) group = line.slice(2).trim();
  else if (line.startsWith("f ")) {
    const idx = line.trim().split(/\s+/).slice(1).map((t) => parseInt(t.split("/")[0], 10) - 1);
    groups[group] ??= new Set();
    for (const i of idx) groups[group].add(i);
    if (group === "body") {
      for (let k = 1; k + 1 < idx.length; k++) bodyFaces.push([idx[0], idx[k], idx[k + 1]]);
    }
  }
}

function shaped(gender) {
  const pos = verts.map((v) => [...v]);
  for (const race of ["african", "asian", "caucasian"]) {
    const text = gunzipSync(readFileSync(path.join(dir, `${race}-${gender}.gz`))).toString("utf8");
    for (const line of text.split("\n")) {
      if (!line || line.startsWith("#")) continue;
      const [i, dx, dy, dz] = line.trim().split(/\s+/).map(Number);
      pos[i][0] += dx / 3; pos[i][1] += dy / 3; pos[i][2] += dz / 3;
    }
  }
  return pos;
}

// compact body vertices
const used = [...new Set(bodyFaces.flat())].sort((a, b) => a - b);
const remap = new Map(used.map((v, i) => [v, i]));
const index = new Uint16Array(bodyFaces.length * 3);
bodyFaces.forEach((f, i) => f.forEach((v, j) => { index[i * 3 + j] = remap.get(v); }));

const JOINTS = {
  pelvis: "joint-pelvis", spine1: "joint-spine-1", spine2: "joint-spine-2", spine3: "joint-spine-3", spine4: "joint-spine-4",
  neck: "joint-neck", head: "joint-head", head2: "joint-head-2",
  "clavicle.L": "joint-l-clavicle", "shoulder.L": "joint-l-shoulder", "elbow.L": "joint-l-elbow", "hand.L": "joint-l-hand", "hand3.L": "joint-l-hand-3",
  "clavicle.R": "joint-r-clavicle", "shoulder.R": "joint-r-shoulder", "elbow.R": "joint-r-elbow", "hand.R": "joint-r-hand", "hand3.R": "joint-r-hand-3",
  "upperLeg.L": "joint-l-upper-leg", "knee.L": "joint-l-knee", "ankle.L": "joint-l-ankle", "foot.L": "joint-l-foot-1", "toe.L": "joint-l-foot-2",
  "upperLeg.R": "joint-r-upper-leg", "knee.R": "joint-r-knee", "ankle.R": "joint-r-ankle", "foot.R": "joint-r-foot-1", "toe.R": "joint-r-foot-2",
};

const out = {};
for (const gender of ["female", "male"]) {
  const pos = shaped(gender);
  // metres, feet on y = 0, centred on the pelvis
  let minY = Infinity;
  for (const v of used) minY = Math.min(minY, pos[v][1]);
  const c = [...groups["joint-pelvis"]].reduce((a, v) => [a[0] + pos[v][0], a[1] + pos[v][2]], [0, 0]);
  const n = groups["joint-pelvis"].size;
  const tx = c[0] / n, tz = c[1] / n;
  const tr = (p) => [(p[0] - tx) * 0.1, (p[1] - minY) * 0.1, (p[2] - tz) * 0.1];
  const body = used.map((v) => tr(pos[v]));
  const min = [0, 1, 2].map((k) => Math.min(...body.map((p) => p[k])));
  const max = [0, 1, 2].map((k) => Math.max(...body.map((p) => p[k])));
  const q = new Uint16Array(body.length * 3);
  body.forEach((p, i) => { for (let k = 0; k < 3; k++) q[i * 3 + k] = Math.round(((p[k] - min[k]) / (max[k] - min[k])) * 65535); });
  const joints = {};
  for (const [name, g] of Object.entries(JOINTS)) {
    const s = [...groups[g]];
    const m = s.reduce((a, v) => { const p = tr(pos[v]); return [a[0] + p[0], a[1] + p[1], a[2] + p[2]]; }, [0, 0, 0]);
    joints[name] = m.map((x) => +(x / s.length).toFixed(4));
  }
  out[gender] = { min, max, pos: Buffer.from(q.buffer).toString("base64"), joints };
  console.log(gender, "height", (max[1] - min[1]).toFixed(3), "m");
}

const ts = `// Generated by scripts/build-human-mesh.mjs. Do not edit.
// Source: MakeHuman base mesh hm08 and macro targets, released under CC0 1.0 by the MakeHuman project.
export const HUMAN = ${JSON.stringify({ vertexCount: used.length, index: Buffer.from(index.buffer).toString("base64"), ...out })} as const;
`;
writeFileSync(path.join(root, "src/components/holo/human-data.ts"), ts);
console.log(`${used.length} vertices, ${bodyFaces.length} triangles, ${(ts.length / 1024).toFixed(0)} KB`);
