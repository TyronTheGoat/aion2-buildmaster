// Bundles Tyron's crafting data package (data/crafting/v5, unchanged copies) into the app as raw CSV text.
// The app parses it with the same importer a user would use. No prices are part of it.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
const root = path.resolve(import.meta.dirname, "..");
const dir = path.join(root, "data/crafting/v5");
// import order: recipes, direct ingredients, transfers, key corrections, chain, gap lists, chance check, price catalogue
const files = [
  "10_IMPORT_FERTIG_Rezepte_Gesamt.csv", "11_IMPORT_FERTIG_Direktzutaten_Gesamt.csv", "03_Transfer_Voraussetzungen.csv",
  "04_V3_Orb_ID_Korrekturen.csv", "09_Orb_Projektkette.csv", "07_Weiterhin_fehlende_V3_Rezepte.csv", "08_V3_Abdeckungsstatus.csv",
  "05_Ergaenzte_80pct_Chancen.csv", "13_PREISOBJEKT_KATALOG_OHNE_PREISE.csv",
];
const out = files.map((f) => [f, readFileSync(path.join(dir, f), "utf8")]);
writeFileSync(path.join(root, "src/lib/crafting/builtin-data.ts"),
  `// Generated by scripts/build-crafting-data.mjs from data/crafting/v5. Do not edit.\nexport const BUILTIN_VERSION = "v5-2026-11-22";\nexport const BUILTIN_FILES: [string, string][] = ${JSON.stringify(out)};\n`);
console.log(`crafting data: ${out.length} files`);
