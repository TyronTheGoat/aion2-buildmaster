// Bundles Tyron's crafting data packages (data/crafting/v5 and v7, unchanged copies) into the app as raw CSV text.
// The app parses them with the same importer a user would use. Prices: only Tyron's Odar reference list (data/crafting/odar),
// imported as marked reference prices that never replace a price the player entered.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
const root = path.resolve(import.meta.dirname, "..");
// import order: V5 (recipes, ingredients, transfers, Orb key fix, confirmed Orb chain, 80 % check, start catalogue),
// then V7 EU/Global (409 recipes, spellbook key fix, ingredients, transfer alternatives, chains, ingredient coverage,
// checked pages, 80 % table, sources, price objects). V5 gap lists 07/08 are replaced by the V7 coverage file.
const files = [
  ["v5", "10_IMPORT_FERTIG_Rezepte_Gesamt.csv"], ["v5", "11_IMPORT_FERTIG_Direktzutaten_Gesamt.csv"], ["v5", "03_Transfer_Voraussetzungen.csv"],
  ["v5", "04_V3_Orb_ID_Korrekturen.csv"], ["v5", "09_Orb_Projektkette.csv"], ["v5", "05_Ergaenzte_80pct_Chancen.csv"], ["v5", "13_PREISOBJEKT_KATALOG_OHNE_PREISE.csv"],
  ["v7", "01_EU_GLOBAL_REZEPTE_409.csv"], ["v7", "09_BESTEHENDE_REZEPT_MAPPING.csv"], ["v7", "02_DIREKTZUTATEN_ZUSAMMEN.csv"], ["v7", "10_TRANSFERALTERNATIVEN_V6.csv"],
  ["v7", "05_EU_PROJEKTKETTEN_V6.csv"], ["v7", "07_DIREKTZUTATEN_ABDECKUNG.csv"], ["v7", "08_EINZELSEITEN_VERIFIZIERT.csv"], ["v7", "03_REZEPT_CHANCEN_80_PROZENT.csv"],
  ["v7", "04_EU_REZEPTQUELLEN.csv"], ["v7", "06_PREISOBJEKTE_MANUELL_OHNE_PREISE.csv"],
  ["odar", "01_PREISOBJEKTE_V7_ODAR_GESAMT.csv"],
];
const out = files.map(([v, f]) => [`${v}/${f}`, readFileSync(path.join(root, "data/crafting", v, f), "utf8")]);
writeFileSync(path.join(root, "src/lib/crafting/builtin-data.ts"),
  `// Generated by scripts/build-crafting-data.mjs from data/crafting/v5, v7 and odar. Do not edit.\nexport const BUILTIN_VERSION = "v7-2026-11-23-orb-screens";\nexport const BUILTIN_FILES: [string, string][] = ${JSON.stringify(out)};\n`);
console.log(`crafting data: ${out.length} files`);
